"""Generates vllc.iss (Inno Setup script) for the VLLC build."""
VIDEO = "mp4 m4v mkv webm avi mov wmv flv mpg mpeg m2v ts m2ts mts 3gp 3g2 ogv vob divx asf rm rmvb f4v".split()
AUDIO = "mp3 flac wav m4a aac ogg oga opus wma ape alac aiff aif mka ac3 dts".split()

head = r'''; VLLC - custom build of VLC media player 4.0-dev (generated by gen_iss.py)
; Per-user install (no admin) into %LOCALAPPDATA%\Programs\VLLC with a
; "portable" folder so settings never mix with an installed VLC 3.

#define AppName "VLLC"
#ifndef AppGuid
  #define AppGuid "6C1C7B9E-3F0E-4D51-9D3A-2B7E5A9C4F11"
#endif
#define AppExe "vllc.exe"
#define AppVersion "4.0.0-dev"
#ifndef SourceDir
  #define SourceDir "S:\Sahil\Projects\vlc\_buildtmp\vllc-pkg"
#endif
#ifndef OutDir
  #define OutDir "S:\Sahil\Projects\vlc"
#endif

[Setup]
AppId={{{#AppGuid}}
AppName={#AppName}
AppVersion={#AppVersion}
AppVerName={#AppName} {#AppVersion}
AppPublisher=VLLC (based on VLC media player by VideoLAN)
DefaultDirName={code:GetDefaultDir}
UsePreviousAppDir=no
DefaultGroupName={#AppName}
DisableProgramGroupPage=yes
PrivilegesRequired=lowest
ArchitecturesAllowed=x64compatible
ArchitecturesInstallIn64BitMode=x64compatible
ChangesAssociations=yes
OutputDir={#OutDir}
OutputBaseFilename=VLLC-{#AppVersion}-win64-setup
SetupIconFile={#SourceDir}\vlc.ico
UninstallDisplayIcon={app}\{#AppExe}
UninstallDisplayName={#AppName}
LicenseFile={#SourceDir}\COPYING.txt
Compression=lzma2/max
SolidCompression=yes
WizardStyle=modern

[Languages]
Name: "english"; MessagesFile: "compiler:Default.isl"

[Tasks]
Name: "desktopicon"; Description: "{cm:CreateDesktopIcon}"; GroupDescription: "{cm:AdditionalIcons}"

[InstallDelete]
; previous name of this build ("VLC Modern"); its folder is removed in [Code]
Type: files; Name: "{autoprograms}\VLC Modern.lnk"
Type: files; Name: "{autodesktop}\VLC Modern.lnk"

[Dirs]
; settings live here instead of %APPDATA%\vlc, keeping VLC 3 untouched
Name: "{app}\portable"

[Files]
Source: "{#SourceDir}\*"; DestDir: "{app}"; Excludes: "\vlc.exe"; Flags: ignoreversion recursesubdirs createallsubdirs
Source: "{#SourceDir}\vlc.exe"; DestDir: "{app}"; DestName: "{#AppExe}"; Flags: ignoreversion

[Icons]
Name: "{autoprograms}\{#AppName}"; Filename: "{app}\{#AppExe}"
Name: "{autodesktop}\{#AppName}"; Filename: "{app}\{#AppExe}"; Tasks: desktopicon

[Registry]
; "Open with" entry for the executable
Root: HKCU; Subkey: "Software\Classes\Applications\{#AppExe}"; ValueType: string; ValueName: "FriendlyAppName"; ValueData: "{#AppName}"; Flags: uninsdeletekey
Root: HKCU; Subkey: "Software\Classes\Applications\{#AppExe}\DefaultIcon"; ValueType: string; ValueData: """{app}\{#AppExe}"",0"
Root: HKCU; Subkey: "Software\Classes\Applications\{#AppExe}\shell\open"; ValueType: string; ValueName: "FriendlyAppName"; ValueData: "{#AppName}"
Root: HKCU; Subkey: "Software\Classes\Applications\{#AppExe}\shell\open\command"; ValueType: string; ValueData: """{app}\{#AppExe}"" --started-from-file ""%1"""
; ProgIDs
Root: HKCU; Subkey: "Software\Classes\VLLC.Video"; ValueType: string; ValueData: "Video file (VLLC)"; Flags: uninsdeletekey
Root: HKCU; Subkey: "Software\Classes\VLLC.Video"; ValueType: string; ValueName: "FriendlyTypeName"; ValueData: "Video file"
Root: HKCU; Subkey: "Software\Classes\VLLC.Video\DefaultIcon"; ValueType: string; ValueData: """{app}\{#AppExe}"",0"
Root: HKCU; Subkey: "Software\Classes\VLLC.Video\shell\open"; ValueType: string; ValueName: "FriendlyAppName"; ValueData: "{#AppName}"
Root: HKCU; Subkey: "Software\Classes\VLLC.Video\shell\open\command"; ValueType: string; ValueData: """{app}\{#AppExe}"" --started-from-file ""%1"""
Root: HKCU; Subkey: "Software\Classes\VLLC.Audio"; ValueType: string; ValueData: "Audio file (VLLC)"; Flags: uninsdeletekey
Root: HKCU; Subkey: "Software\Classes\VLLC.Audio"; ValueType: string; ValueName: "FriendlyTypeName"; ValueData: "Audio file"
Root: HKCU; Subkey: "Software\Classes\VLLC.Audio\DefaultIcon"; ValueType: string; ValueData: """{app}\{#AppExe}"",0"
Root: HKCU; Subkey: "Software\Classes\VLLC.Audio\shell\open"; ValueType: string; ValueName: "FriendlyAppName"; ValueData: "{#AppName}"
Root: HKCU; Subkey: "Software\Classes\VLLC.Audio\shell\open\command"; ValueType: string; ValueData: """{app}\{#AppExe}"" --started-from-file ""%1"""
; Default Apps (Settings > Apps > Default apps > VLLC)
Root: HKCU; Subkey: "Software\VLLC"; Flags: uninsdeletekey
Root: HKCU; Subkey: "Software\VLLC\Capabilities"; ValueType: string; ValueName: "ApplicationName"; ValueData: "{#AppName}"
Root: HKCU; Subkey: "Software\VLLC\Capabilities"; ValueType: string; ValueName: "ApplicationDescription"; ValueData: "VLLC media player"
Root: HKCU; Subkey: "Software\VLLC\Capabilities"; ValueType: string; ValueName: "ApplicationIcon"; ValueData: """{app}\{#AppExe}"",0"
Root: HKCU; Subkey: "Software\RegisteredApplications"; ValueType: string; ValueName: "VLLC"; ValueData: "Software\VLLC\Capabilities"; Flags: uninsdeletevalue
'''

lines = []
for kind, exts in (("Video", VIDEO), ("Audio", AUDIO)):
    for e in exts:
        lines.append(f'Root: HKCU; Subkey: "Software\\Classes\\.{e}\\OpenWithProgids"; ValueType: string; ValueName: "VLLC.{kind}"; ValueData: ""; Flags: uninsdeletevalue')
        lines.append(f'Root: HKCU; Subkey: "Software\\Classes\\Applications\\{{#AppExe}}\\SupportedTypes"; ValueType: string; ValueName: ".{e}"; ValueData: ""')
        lines.append(f'Root: HKCU; Subkey: "Software\\VLLC\\Capabilities\\FileAssociations"; ValueType: string; ValueName: ".{e}"; ValueData: "VLLC.{kind}"')

tail = r'''
[Code]
var
  PrevDir: String;

function InitializeSetup(): Boolean;
begin
  { location of a previous install of this AppId ("VLC Modern" or VLLC) }
  if not RegQueryStringValue(HKCU, 'Software\Microsoft\Windows\CurrentVersion\Uninstall\{{#AppGuid}}_is1',
                             'InstallLocation', PrevDir) then
    PrevDir := '';
  PrevDir := RemoveBackslash(PrevDir);
  Result := True;
end;

function GetDefaultDir(Param: String): String;
begin
  { install next to the previous version (e.g. S:\VLC\VLC Modern -> S:\VLC\VLLC) }
  if PrevDir <> '' then
    Result := AddBackslash(ExtractFileDir(PrevDir)) + 'VLLC'
  else
    Result := ExpandConstant('{localappdata}\Programs\VLLC');
end;

procedure CurStepChanged(CurStep: TSetupStep);
begin
  if (CurStep = ssPostInstall) and (PrevDir <> '')
     and (CompareText(PrevDir, RemoveBackslash(ExpandConstant('{app}'))) <> 0)
     and FileExists(PrevDir + '\vlc.exe') then
    DelTree(PrevDir, True, True, True);
end;


[Run]
; rebuild the plugin cache for this install location (faster startup)
Filename: "{app}\vlc-cache-gen.exe"; Parameters: """{app}\plugins"""; Flags: runhidden
Filename: "{app}\{#AppExe}"; Description: "{cm:LaunchProgram,{#AppName}}"; Flags: nowait postinstall skipifsilent

[UninstallDelete]
Type: filesandordirs; Name: "{app}\portable"
Type: filesandordirs; Name: "{app}\plugins\plugins.dat"
'''

with open(__file__.replace("gen_iss.py", "vllc.iss"), "w", encoding="utf-8", newline="\r\n") as f:
    f.write(head + "\n".join(lines) + "\n" + tail)
print("written")
